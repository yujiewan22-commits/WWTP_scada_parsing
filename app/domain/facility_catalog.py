def facility_catalog_prompt_text() -> str:
    lines = []
    for item in FACILITY_CATALOG:
        lines.append(f'{item["code"]} {item["name"]}：{item["remark"]}')
    return "\n".join(lines)


def facility_name_by_code(code: str) -> str | None:
    code = str(code).zfill(2)
    for item in FACILITY_CATALOG:
        if item["code"] == code:
            return item["name"]
    return None
